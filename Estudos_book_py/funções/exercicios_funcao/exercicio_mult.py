# crie uma funçãio que duplique, triplique e quadruplique


def multiplica(number1):
        numeros_duplicado = number1 * 2
        numeros_triplicado = number1 * 3
        numeros_quadriplicado = number1 * 4
        number_final = numeros_duplicado + numeros_triplicado + numeros_quadriplicado   
        return number_final

